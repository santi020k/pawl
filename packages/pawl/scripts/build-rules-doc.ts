/**
 * Writes the rules reference page of the docs site from the catalog, and the counts the landing page shows.
 * Run with: pnpm run docs:rules
 */
import { writeFileSync } from 'node:fs'
import { GUARDS } from '../src/catalog/guards.ts'
import { PACKS } from '../src/catalog/packs.ts'
import { GATED_TAGS, RULES, type RuleDef, type RuleTag } from '../src/catalog/rules.ts'
import { DOCKER_RULES } from '../src/scans/docker.ts'

const TITLES: Partial<Record<RuleTag, string>> = {
  core: 'JavaScript',
  typescript: 'TypeScript',
  react: 'React',
  qwik: 'Qwik',
  vue: 'Vue',
  svelte: 'Svelte',
  imports: 'Imports and dependencies',
  tests: 'Tests',
  formats: 'Markdown and YAML',
  turbo: 'Turborepo',
  pawl: 'Pawl'
}

const NOTES: Partial<Record<RuleTag, string>> = {
  react: 'Applied only where React is a dependency.',
  qwik: 'Applied only where Qwik is a dependency.',
  vue: 'Applied only where Vue or Nuxt is a dependency.',
  svelte: 'Applied only where Svelte is a dependency.',
  turbo: 'Applied only in a Turborepo.',
  pawl: 'Checked by pawl itself, on top of the engines.'
}

const level = (rule: RuleDef): string =>
  rule.strict && rule.strict !== rule.level ? `${rule.level} (${rule.strict} when strict)` : rule.level

const row = (rule: RuleDef): string => {
  const unstable = rule.nursery ? `unstable in ${rule.biome ? 'Biome' : 'Oxlint'}` : ''
  const engine = !rule.biome && rule.tag !== 'pawl' ? 'Oxlint or an ESLint plugin' : ''
  const marks = [rule.guardrail ? 'guardrail' : '', unstable, engine].filter(Boolean).join(', ')

  return `| \`${rule.name}\` | ${rule.summary.replaceAll('|', '\\|').replaceAll('<', '&lt;')} | ${level(rule)} | ${rule.biome ? `\`${rule.biome}\`` : ''} | ${marks} |`
}

const lines = [
  '---',
  'title: Rules',
  `description: "All ${RULES.length} rules in the pawl standard, under ESLint's names: what each one checks, its level, and the Biome rule that enforces it."`,
  // Flow style, on one line: Biome formats the front matter of a Markdown file as Markdown.
  `head: [{ tag: title, content: "Rules: the ${RULES.length} lint rules and their Biome equivalents | pawl" }]`,
  '---',
  '',
  '<!-- Generated by packages/pawl/scripts/build-rules-doc.ts. Do not edit by hand. -->',
  '',
  `The standard has ${RULES.length} rules. Names are ESLint's names; use them in \`rules\` in a policy. Run \`pawl explain <rule>\` to see a rule's level in your repo.`,
  '',
  `On top of these, pawl turns on Biome's own recommended rules for each technology a project uses: ${GATED_TAGS.join(', ')}.`,
  '',
  'A **guardrail** rule guards against a mistake coding agents make often. A rule that is **unstable** in the engine that enforces it is off unless the policy is strict. A rule with no Biome rule is enforced by Oxlint, or by ESLint with the plugin installed.',
  ''
]

for (const tag of Object.keys(TITLES) as RuleTag[]) {
  const rules = RULES.filter(rule => rule.tag === tag)

  if (rules.length === 0) continue

  lines.push(`## ${TITLES[tag] ?? tag}`, '')

  if (NOTES[tag]) lines.push(NOTES[tag], '')

  lines.push(
    '| Rule | What it checks | Level | Biome rule | Notes |',
    '| --- | --- | --- | --- | --- |',
    ...rules.map(row),
    ''
  )
}

const target = new URL('../../../apps/docs/src/content/docs/reference/rules.md', import.meta.url)

writeFileSync(target, lines.join('\n'))
process.stdout.write(`Wrote ${RULES.length} rules to apps/docs/src/content/docs/reference/rules.md\n`)

// The docs deploy builds the site without building pawl, so the landing page reads its numbers from this committed file.
const counts = { rules: RULES.length, packs: PACKS.length, dockerChecks: DOCKER_RULES.length, guards: GUARDS.length }

writeFileSync(
  new URL('../../../apps/docs/src/data/counts.json', import.meta.url),
  `${JSON.stringify(counts, null, 2)}\n`
)
process.stdout.write('Wrote apps/docs/src/data/counts.json\n')
